# Measured over all 24,129 BP labels: r"\bactivated\b" matched 88 terms and not one
# encoded a direction. r"\binhibited\b" matched none.
NOT_DIRECTIONAL_PAST_PARTICIPLE = [
    "peroxisome proliferator activated receptor signaling pathway",
    "angiotensin-activated signaling pathway",
    "TRAIL-activated apoptotic signaling pathway",
    "VEGF-activated neuropilin signaling pathway",
    "CXCL12-activated CXCR4 signaling pathway",
    "abscisic acid-activated signaling pathway",
    "activated T cell proliferation",
    "activated CD4-positive, alpha-beta T cell apoptotic process",
    "calcium activated phospholipid scrambling",
]


@pytest.mark.parametrize("name", NOT_DIRECTIONAL_PAST_PARTICIPLE)
def test_past_participle_qualifiers_are_not_directional(name):
    """"X-activated Y" names a ligand or a cell state, it does not sign the term."""
    assert is_directional_go_label(name) is False


@pytest.mark.parametrize(
    "name",
    [
        "positive regulation of activated T cell proliferation",
        "negative regulation of peroxisome proliferator activated receptor signaling pathway",
        "positive regulation of apoptotic process",
        "activation of protein kinase activity",
    ],
)
def test_genuinely_signed_labels_are_still_directional(name):
    """The regulation patterns already catch the signed variants of the above."""
    assert is_directional_go_label(name) is True


def test_ligand_activated_pathways_survive_fuzzy_search():
    """The runtime guard also filters search results, so the corrected regex is
    what actually lets these terms reach a curator."""
    index = {
        "GO:0038166": {
            "name": "angiotensin-activated signaling pathway",
            "definition": "A series of molecular signals initiated by angiotensin.",
        },
        "GO:0001234": {
            "name": "positive regulation of angiotensin-activated signaling pathway",
            "definition": "Any process that increases the above.",
        },
    }
    svc = _service(search_index=index)
    hits = {r["go_id"] for r in svc.search_go_terms("angiotensin-activated signaling pathway", threshold=0.2)}
    assert "GO:0038166" in hits
    assert "GO:0001234" not in hits, "the signed variant must still be excluded"


# ---------------------------------------------------------------------------
# Corpus build: definitions are parsed, and the search index spans the namespace
# ---------------------------------------------------------------------------

MINI_OBO = """format-version: 1.2

[Term]
id: GO:0035357
name: peroxisome proliferator activated receptor signaling pathway
namespace: biological_process
def: "A series of molecular signals generated by a PPAR binding its ligand." [GOC:signaling]
is_a: GO:0030522 ! intracellular receptor signaling pathway

[Term]
id: GO:0006281
name: DNA repair
namespace: biological_process
def: "The process of restoring damaged DNA, involving \\"excision\\" steps." [GOC:go_curators]
is_a: GO:0006259 ! DNA metabolic process

[Term]
id: GO:0000003
name: obsolete thing
namespace: biological_process
def: "Do not use." [GOC:x]
is_obsolete: true

[Term]
id: GO:0003674
name: molecular_function
namespace: molecular_function
def: "A molecular process." [GOC:x]
"""


def test_obo_parser_extracts_definitions(tmp_path):
    """Search fuzzy-matches on definitions, so the corpus build must carry them."""
    from scripts import precompute_go_hierarchy as pgh

    obo = tmp_path / "mini.obo"
    obo.write_text(MINI_OBO, encoding="utf-8")
    terms, _ = pgh.parse_obo_file(str(obo), namespace_value="biological_process")

    assert set(terms) == {"GO:0035357", "GO:0006281"}, "obsolete and MF terms excluded"
    assert terms["GO:0035357"]["definition"].startswith("A series of molecular signals")
    # The trailing [xref] list is not searchable text and must be stripped, while
    # quotes inside the definition body are preserved.
    assert "[GOC:" not in terms["GO:0006281"]["definition"]
    assert terms["GO:0006281"]["definition"].endswith('steps.') or \
        'excision' in terms["GO:0006281"]["definition"]


def test_parsed_terms_feed_a_full_namespace_search_index(tmp_path):
    """The index the app searches is built straight off the parsed terms, so a
    gene-count-filtered term is still present in it."""
    from scripts import precompute_go_hierarchy as pgh

    obo = tmp_path / "mini.obo"
    obo.write_text(MINI_OBO, encoding="utf-8")
    terms, _ = pgh.parse_obo_file(str(obo), namespace_value="biological_process")

    search_index = {
        go_id: {"name": data["name"], "definition": data.get("definition") or ""}
        for go_id, data in terms.items()
    }
    svc = _service(search_index=search_index)
    assert [r["go_id"] for r in svc.search_go_terms("GO:0035357")] == ["GO:0035357"]
    assert [r["go_id"] for r in svc.search_go_terms("GO:0006281")] == ["GO:0006281"]
